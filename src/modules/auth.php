<?php
/**
 * Общие помощники сессии.
 *
 * Подключается через modules/connect.php, который тянут все страницы.
 */

if (!function_exists('logout_user')) {
    /**
     * Полный сброс сессии: данные, cookie, сама сессия.
     *
     * Сброс нужен в двух случаях, и раньше это был один и тот же код в двух
     * файлах: человек нажал «Выйти» и его сессию сбросили руками, а во
     * втором случае сессия пережила удаление пользователя из базы, и её
     * пришлось сбрасывать на лету, иначе удалённый пользователь получал
     * пустой профиль вместо формы входа.
     *
     * Вызывать надо при активной сессии: session_start() до вызова.
     * Редирект и exit остаются на стороне вызывающего - здесь только сброс,
     * чтобы вызывающий сам решал, куда отправлять.
     */
    function logout_user(): void
    {
        $_SESSION = [];
        if (ini_get('session.use_cookies')) {
            $p = session_get_cookie_params();
            setcookie(session_name(), '', time() - 42000,
                $p['path'], $p['domain'], $p['secure'], $p['httponly']);
        }
        session_destroy();
    }
}