 * конденсаторы, и всё сливалось в одно тёмное поле. Круглые детали
 * меньше радиуса 1.2 при отображении 28px тоже не дают пикселя и
 * только плодят шум, поэтому таких нет вовсе - проверяет тест.
 * Итог: деталь оставлена там, где она переживает уменьшение.
 *
 * Почему inline, а не <use href="icons.svg#i-cpu">: внешний спрайт
 * грузится через fetch и требует корректный MIME и
 * Access-Control-Allow-Origin, без которых иконки не появляются
 * вообще и молча - без ошибки в консоли. И currentColor из
 * вызывающей страницы в <use> из внешнего документа не наследуется.
 * Вариант с <img src="...svg"> не наследует цвет тем более.
 */

