 *    детали: корпус, разъёмы, вентиляторы.
 * 3. Выделенная деталь - заливка opacity 0.8, ровно одна на иконку.
 *    То, что делает компонент собой: ядро процессора, сокет платы,
 *    вентилятор видеокарты.
 *
 * Выбор между контуром и duotone был неочевиден, поэтому проверен
 * замером, а не на глаз: иконки отрисованы в canvas ровно в том
 * размере, в каком показываются на карточке, и выписаны попиксельно.
