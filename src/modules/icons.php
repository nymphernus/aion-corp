<?php
/**
 * Иконки конфигуратора (Stage 7.5).
 *
 * Десять контурных иконок в едином стиле: viewBox 0 0 24 24,
 * stroke-width 1.5, скруглённые концы, только currentColor. Раньше
 * это были десять png по 6-32 КБ, и цвет они имели фиксированный:
 * сменить акцент темы - значило перерисовывать картинки.
 *
 * Почему inline, а не <use href="icons.svg#i-cpu">: внешний спрайт
 * грузится через fetch и требует корректный MIME и
 * Access-Control-Allow-Origin, без которых иконки не появляются
 * вообще и молча - без ошибки в консоли. И currentColor из
 * вызывающей страницы в <use> из внешнего документа не наследуется.
 * Вариант с <img src="...svg"> не наследует цвет тем более.
 */

if (!function_exists('icon')) {
    /**
     * Иконка конфигуратора.
     *
     * Имена в массиве - короткие и английские, потому что это ключи
     * в разметке: icon('cpu'), icon('ram'). Подписи «Процессор»,
     * «Оперативная память» - это $label рядом, он переводится и
     * зависит от языка, а ключ не должен.
     *
     * Строка выводится целиком через <?= : это собственная разметка
     * проекта, escape() на ней бы ломал кавычки атрибутов.
     *
     * @param string $name   ключ из списка
     * @param int    $size   сторона квадрата, px
     * @param string $class  класс для CSS, можно несколько через пробел
     * @return string svg или пустая строка, если ключа нет
     */
    function icon(string $name, int $size = 24, string $class = ''): string
    {
        // Общая оболочка. Восемь частей каждой иконки совпадают, и
        // расходиться они не могут: иначе одна иконка получится с
        // квадратными концами, а соседняя со скруглёнными, и разницу
        // видно только при сравнении рядом. Атрибутов девять, писать
        // их у каждой иконки - гарантия, что однажды забудется
        // stroke-linecap у новой.
        $wrap = static fn(string $body): string => '<svg class="icon ' . escape($class)
            . '" width="' . (int) $size . '" height="' . (int) $size . '"'
            . ' viewBox="0 0 24 24" fill="none" stroke="currentColor"'
            . ' stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"'
            . ' aria-hidden="true" focusable="false">' . $body . '</svg>';

        static $icons = [

            // Процессор. Квадрат корпуса, внутри ядро, по периметру
            // ножки - четыре пары, по две на сторону.
            'cpu' => '<rect x="4.5" y="4.5" width="15" height="15" rx="2"></rect>'
                . '<rect x="9" y="9" width="6" height="6" rx="1"></rect>'
                . '<path d="M9 1.5v3M15 1.5v3M9 19.5v3M15 19.5v3"></path>'
                . '<path d="M1.5 9h3M1.5 15h3M19.5 9h3M19.5 15h3"></path>',

            // Материнская плата. Плата прямоугольником, чип и разъёмы
            // на месте: без дорожек это был бы пустой прямоугольник.
            'mb' => '<rect x="2.5" y="4" width="19" height="16" rx="2"></rect>'
                . '<rect x="6" y="8" width="7" height="7" rx="1"></rect>'
                . '<path d="M17 8.5h1.5M17 11h1.5M17 13.5h1.5"></path>'
                . '<path d="M6 19h3M11 19h3M16 19h2.5"></path>'
                . '<circle cx="18.5" cy="17" r="1.5"></circle>',

            // Видеокарта. Плата в профиль, вентилятор кругом, крепление
            // сверху - вертикальной чертой, как у настоящей карты.
            'gpu' => '<rect x="2.5" y="5" width="19" height="14" rx="2"></rect>'
                . '<circle cx="9" cy="12" r="4"></circle>'
                . '<path d="M9 8v4l2.5 2"></path>'
                . '<path d="M17 8v8M20 8v8"></path>'
                . '<path d="M6 19v1.5M12 19v1.5"></path>',

            // Оперативная память. Длинная планка с зубчатым краем
            // снизу, чипы сверху - это то, чем планка отличается от
            // просто прямоугольника.
            'ram' => '<rect x="2" y="7" width="20" height="10" rx="1.5"></rect>'
                . '<rect x="5" y="9.5" width="3.5" height="3.5"></rect>'
                . '<rect x="10.25" y="9.5" width="3.5" height="3.5"></rect>'
                . '<rect x="15.5" y="9.5" width="3.5" height="3.5"></rect>'
                . '<path d="M6 17v3M9 17v2M12 17v3M15 17v2M18 17v3"></path>',

            // Блок питания. Корпус, вентилятор, разъём сзади щелью -
            // визитная карточка БП.
            'psu' => '<rect x="2.5" y="4" width="19" height="16" rx="2"></rect>'
                . '<circle cx="9" cy="12" r="4.5"></circle>'
                . '<path d="M9 7.5v4.5h4"></path>'
                . '<path d="M16 8h4M16 11h4M16 14h4"></path>'
                . '<path d="M5 20v1.5M19 20v1.5"></path>',

            // Корпус. Боковая панель с кнопкой питания и щелями
            // вентиляции: кнопка круглая сверху, слоты ниже.
            'case' => '<rect x="4" y="2.5" width="16" height="19" rx="2"></rect>'
                . '<circle cx="8.5" cy="7" r="1.75"></circle>'
                . '<path d="M13 6h4M13 8h4"></path>'
                . '<circle cx="8.5" cy="15" r="3.5"></circle>'
                . '<path d="M8.5 11.5v7M5 15h7"></path>',

            // Кулер. Квадрат рамки и четыре лопасти крест-накрест -
            // отличить от блока питания можно только по лопастям.
            'cooler' => '<rect x="3" y="3" width="18" height="18" rx="2"></rect>'
                . '<circle cx="12" cy="12" r="1.75"></circle>'
                . '<path d="M12 6.5c2.5 0 4.5 1.4 4.5 3.2 0 1-.6 1.8-1.5 2.3"></path>'
                . '<path d="M17.5 12c0 2.5-1.4 4.5-3.2 4.5-1 0-1.8-.6-2.3-1.5"></path>'
                . '<path d="M12 17.5c-2.5 0-4.5-1.4-4.5-3.2 0-1 .6-1.8 1.5-2.3"></path>'
                . '<path d="M6.5 12c0-2.5 1.4-4.5 3.2-4.5 1 0 1.8.6 2.3 1.5"></path>',

            // Жёсткий диск. Корпус с округлением, сверху пластина со
            // шпинделем - вид сверху.
            'hdd' => '<rect x="2.5" y="4.5" width="19" height="15" rx="2"></rect>'
                . '<ellipse cx="12" cy="11" rx="6.5" ry="4.5"></ellipse>'
                . '<circle cx="12" cy="11" r="1.5"></circle>'
                . '<path d="M5.5 16.5h4M11.5 16.5h2.5M15.5 16.5h3"></path>',

            // SSD. Тонкая пластина сверху и контактная площадка
            // золотом не нарисовать - плоский прямоугольник с чипами
            // отличается от планки памяти толщиной.
            'ssd' => '<rect x="2" y="7.5" width="20" height="9" rx="1.5"></rect>'
                . '<rect x="5" y="10" width="4" height="4" rx="0.75"></rect>'
                . '<rect x="10" y="10" width="4" height="4" rx="0.75"></rect>'
                . '<path d="M15.5 10h3.5v4h-3.5z"></path>'
                . '<path d="M6 16.5v2M9 16.5v3M12 16.5v2M15 16.5v3M18 16.5v2"></path>',

            // Операционная система. Монитор с окном внутри - окно и
            // есть то, чем ось отличается от прочих компонентов.
            // Логотипы Windows, Linux и Apple здесь были бы уместны,
            // но это чужие торговые знаки: рисуем абстракцию.
            'os' => '<rect x="2.5" y="4" width="19" height="13" rx="2"></rect>'
                . '<rect x="5.5" y="7" width="13" height="7" rx="1"></rect>'
                . '<path d="M8 17v2.5M16 17v2.5M7 19.5h10"></path>',
        ];

        if (!isset($icons[$name])) {
            return '';
        }

        return $wrap($icons[$name]);
    }
}