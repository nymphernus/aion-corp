 * в сплошное пятно, а контактные площадки радиуса 0.8 не давали даже
 * половины пикселя и совпадали с линиями ножек. Duotone на 24 и 28px
 * читается однозначно: подложка, контур и сплошная деталь дают
 * узнаваемый силуэт.
 *
 * Тот же замер гонял и по детализации. Первая версия была подробнее
 * всех пожеланий сразу, и мерная карта показала: mb давала 167 тёмных
 * пикселей против 75-80 у остальных, то есть вдвое больше - плата
